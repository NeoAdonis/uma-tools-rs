//! Last spurt calculation logic.

use rand::RngExt;

use crate::configuration::GameVersion;
use crate::course::{Course, Phase};
use crate::race::hp::{
    calculate_hp_per_second, estimate_hp_last_spurt, estimate_hp_per_meter_last_spurt,
};
use crate::race::modifiers::*;
use crate::race::runner::Runner;
use crate::race::solver::RaceState;

/// Parameters defining the last spurt behavior of a runner.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct LastSpurt {
    /// Maximum speed achievable during the last spurt (m/s).
    pub max_speed: f64,
    /// Distance at which the last spurt starts (m).
    pub target_distance: f64,
    /// Category of last spurt based on achievable speed and HP.
    pub category: LastSpurtCategory,
}

/// Category of last spurt based on achievable speed and HP.
///
/// Values match those of the `lastspurt` condition variable.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum LastSpurtCategory {
    /// Last spurt cannot be fully carried out even at base target speed.
    CannotFinish = 0,
    /// Last spurt can be carried out above base target speed but not at max speed.
    AboveBase = 1,
    /// Last spurt can be carried out at max speed without HP issues.
    Full = 2,
}

/// Candidate last spurt option during calculation.
struct LastSpurtCandidate {
    speed: f64,
    distance: f64,
    time: f64,
}

/// Calculate the maximum possible last spurt speed for a runner.
fn last_spurt_speed_max(runner: &Runner, state: &RaceState) -> f64 {
    let base_speed = state.course.base_speed();
    let stats = &runner.adjusted;
    let distance_aptitude = runner.raw.distance_aptitude;
    let base_target_late = base_target_speed(
        base_speed,
        runner.style,
        Phase::Late,
        stats.speed,
        distance_aptitude,
    );
    let base_component = (base_target_late + 0.01 * base_speed) * 1.05;
    let speed_component =
        (500.0 * stats.speed).sqrt() * distance_proficiency_multiplier(distance_aptitude) * 0.002;
    let guts_component = if state.config.game_version < GameVersion::FirstAnniversary {
        0.0
    } else {
        (450.0 * stats.guts).powf(0.597) * 0.0001
    };
    base_component + speed_component + guts_component
}

/// Remaining distance from the start of the Late phase (or current position, if
/// later) to the goal line.
fn remaining_spurt_distance(runner: &Runner, course: &Course) -> f64 {
    (course.length() - Phase::Late.boundaries(course).0).min(course.length() - runner.position)
}

/// HP required to run the last spurt at `speed` until 60m before the goal line.
fn spurt_hp_required(runner: &Runner, state: &RaceState, speed: f64) -> f64 {
    estimate_hp_last_spurt(
        speed,
        &state.course,
        state.params.track_condition,
        remaining_spurt_distance(runner, &state.course) - 60.0,
        runner.adjusted.guts,
    )
}

impl Runner {
    /// Estimate the HP required to finish the race from the current position.
    ///
    /// It is the HP needed to run the rest of the Mid phase at its base target
    /// speed, plus the HP needed for a last spurt at max speed (as estimated by
    /// [`Self::calculate_last_spurt`]).
    // ? Assumed to be "required amount to finish the race" as used by Stamina Keep.
    pub(crate) fn hp_required_to_finish(&self, state: &RaceState) -> f64 {
        let course = &state.course;
        let mid_distance = (Phase::Late.boundaries(course).0 - self.position).max(0.0);
        let mid_speed = base_target_speed(
            course.base_speed(),
            self.style,
            Phase::Mid,
            self.adjusted.speed,
            self.raw.distance_aptitude,
        );
        let mid_hp = calculate_hp_per_second(
            mid_speed,
            course,
            state.params.track_condition,
            Phase::Mid,
            self.adjusted.guts,
            1.0,
        ) * mid_distance
            / mid_speed;
        mid_hp + spurt_hp_required(self, state, last_spurt_speed_max(self, state))
    }

    /// Calculate the last spurt parameters of this runner.
    ///
    /// The last spurt is a burst of speed towards the end of the race. It is
    /// determined based on the runner's stats, remaining HP, and course conditions.
    ///
    /// First, the maximum possible last spurt speed is calculated. If the runner
    /// has enough HP to sustain this speed, it is immediately set as the last spurt
    /// speed. Otherwise, a list of candidate last spurt speeds is generated by
    /// decrementing from the maximum speed down to the late-race base target speed.
    /// For each candidate speed, the distance that can be covered with the
    /// remaining HP is estimated, and from there, the total time to finish the
    /// race. A candidate is picked based on a probability influenced by the
    /// runner's wit stat. A higher wit increases the chance of picking a
    /// higher speed.
    pub(crate) fn calculate_last_spurt(&mut self, state: &RaceState) -> LastSpurt {
        let course = &state.course;
        let track_condition = state.params.track_condition;
        let max_last_spurt_speed = last_spurt_speed_max(self, state);

        // Calculate remaining distance from start of late phase (or current position).
        let remaining_distance = remaining_spurt_distance(self, course);

        // Estimate stamina usage up to 60m before goal line.
        let calculation_distance = remaining_distance - 60.0;

        // If HP is sufficient for max speed, use it immediately.
        let max_hp_required = spurt_hp_required(self, state, max_last_spurt_speed);

        if self.hp.current() >= max_hp_required {
            return LastSpurt {
                max_speed: max_last_spurt_speed,
                target_distance: course.length() - remaining_distance,
                category: LastSpurtCategory::Full,
            };
        }

        // Use late-race base target speed as minimum speed.
        let late_base_target_speed = base_target_speed(
            course.base_speed(),
            self.style,
            Phase::Late,
            self.adjusted.speed,
            self.raw.distance_aptitude,
        );

        let hp_rate_base = estimate_hp_per_meter_last_spurt(
            late_base_target_speed,
            course,
            track_condition,
            self.adjusted.guts,
        );

        // Numerator for last spurt distance calculation.
        // It equals the remaining HP after running calculation distance at base speed,
        // so it can also be used to check if the runner can even finish at base speed.
        let numerator = self.hp.current() - calculation_distance * hp_rate_base;
        if numerator <= 0.0 {
            return LastSpurt {
                max_speed: late_base_target_speed,
                target_distance: course.length() - 60.0,
                category: LastSpurtCategory::CannotFinish,
            };
        }

        // Build list of candidates by lowering speed by 0.1 m/s each step. Max speed is
        // always above late-race base target speed, so the list is never empty.
        let mut candidates = Vec::new();
        for step in 0.. {
            let test_speed = max_last_spurt_speed - 0.1 * step as f64;
            if test_speed < late_base_target_speed {
                break;
            }

            let hp_rate_spurt = estimate_hp_per_meter_last_spurt(
                test_speed,
                course,
                track_condition,
                self.adjusted.guts,
            );

            // Spurt distance `d` that uses up the HP, running the rest of the calculation
            // distance at base speed:
            //
            // current_hp = (calculation_distance - d) * hp_rate_base + d * hp_rate_spurt
            //
            // Solving for `d` gives:
            // d = numerator / (hp_rate_spurt - hp_rate_base)
            //
            // HP per meter grows with speed, and candidates are never below the base speed,
            // so with `numerator > 0` (checked above), `d` is positive, or infinite at the
            // base speed, before being clamped.
            let last_spurt_distance =
                (numerator / (hp_rate_spurt - hp_rate_base)).min(calculation_distance);

            // Add back the final 60m that we excluded from calculations.
            let last_spurt_distance_with_final = last_spurt_distance + 60.0;

            // Calculate time to finish (ignoring acceleration):
            // Last spurt duration at tested speed + time to traverse remaining distance at
            // late-race base speed.
            let remaining_at_base = remaining_distance - last_spurt_distance_with_final;

            let time = last_spurt_distance_with_final / test_speed
                + remaining_at_base / late_base_target_speed;

            candidates.push(LastSpurtCandidate {
                speed: test_speed,
                distance: last_spurt_distance_with_final,
                time,
            });
        }

        let acceptance_chance = (0.15 + 0.0005 * self.adjusted.wit).min(1.0);
        let rng = &mut self.rng;

        // Try each candidate from best to worst.
        candidates.sort_by(|a, b| a.time.total_cmp(&b.time));
        for candidate in &candidates {
            if rng.last_spurt.random_bool(acceptance_chance) {
                return LastSpurt {
                    max_speed: candidate.speed,
                    target_distance: course.length() - candidate.distance,
                    category: LastSpurtCategory::AboveBase,
                };
            }
        }

        // If all checks fail, use the slowest (last) candidate.
        let last = candidates.last().expect("max speed is always a candidate");
        LastSpurt {
            max_speed: last.speed,
            target_distance: course.length() - last.distance,
            category: LastSpurtCategory::AboveBase,
        }
    }
}

