#!/usr/bin/env perl

use v5.36;

use DBI;
use DBD::SQLite::Constants qw(:file_open);
use Hash::Util             qw(lock_hash);
use List::Util             qw(max);

@ARGV or die "Usage: make_skill_level_values.pl master.mdb\n";
my ($mastermdb) = @ARGV;

my $db = DBI->connect(
    "dbi:SQLite:$mastermdb",
    undef, undef,
    {
        RaiseError        => 1,
        sqlite_open_flags => SQLITE_OPEN_READONLY
    }
);

# Types from 500 onward belong to non-race skills, and don't fit in `SkillType`.
my $select = $db->prepare(
    <<"SQL"
SELECT ability_type, level, float_ability_value_coef
  FROM skill_level_value
  WHERE ability_type < 500;
SQL
);

$select->execute;

# Coefficients in ten-thousandths, by ability type, then level.
my %coefs;

while ( my $row = $select->fetchrow_hashref ) {

    # `die` on misspelled column names instead of silently reading undef.
    lock_hash( $row->%* );
    $coefs{ $row->{ability_type} }{ $row->{level} } =
      $row->{float_ability_value_coef};
}

%coefs or die "No skill level values found\n";

my $max_type  = max keys %coefs;
my $max_level = max map { keys $_->%* } values %coefs;

# Every type must have every level, so that each row is complete.
for my $type ( sort { $a <=> $b } keys %coefs ) {
    for my $level ( 1 .. $max_level ) {
        exists $coefs{$type}{$level}
          or die "Missing level $level for ability type $type\n";
    }
}

# Multiplier as a Rust float literal, e.g. 1.0 or 1.18.
sub multiplier($coef) {
    my $value = sprintf '%.4f', $coef / 10000;
    $value =~ s/0+$//;
    $value =~ s/\.$/.0/;
    return $value;
}

my @rows = map {
    my $type = $_;
    exists $coefs{$type}
      ? '['
      . join( ', ', map { multiplier( $coefs{$type}{$_} ) } 1 .. $max_level )
      . '],'
      : "[1.0; $max_level],";
} 0 .. $max_type;

# Align the type comments as `rustfmt` does.
my $width = max map { length } @rows;
my $rows  = join '',
  map { sprintf "    %-${width}s // %d\n", $rows[$_], $_ } 0 .. $max_type;

my $types = $max_type + 1;

print <<"RUST";
//! Skill effect multipliers by skill level, from the game's
//! `skill_level_value` table.
//!
//! Generated by `scripts/make_skill_level_values.pl`; don't edit by hand.

/// Effect multipliers by skill level, indexed by
/// [`SkillType`](crate::skill::SkillType) ID, then by level minus 1 (i.e. the
/// first column is level 1). Types missing from the game's table are 1x at
/// every level.
pub(super) const LEVEL_MULTIPLIERS: [[f64; $max_level]; $types] = [
$rows];
RUST
